export function createActiveSessionFromRoutine(
  routine: Routine,
  dayId: string,
  preCompleteFirstCount = 0
): WorkoutSession {
  const day = routine.days.find((d) => d.id === dayId) ?? routine.days[0];

  return {
    id: `active-${day.id}`,
    routineId: routine.id,
    routineDayId: day.id,
    dayShortLabel: day.shortLabel,
    dayTitle: day.fullTitle,
    startedAt: new Date().toISOString(),
    durationMin: routine.durationTargetMin,
    rpe: routine.baselineRpe,
    totalVolumeKg: 0,
    validSetsCount: 0,
    status: 'in_progress',
    exercises: day.exercises.map((ex, idx) => {
      const done = idx < preCompleteFirstCount;
      const defaultRirNum = parseInt(ex.targetRir, 10) || 1;
      const defaultReps = done ? ex.maxReps : ex.minReps;
      return {
        plannedExerciseId: ex.id,
        exerciseId: ex.exerciseId,
        name: ex.name,
        subtitle: ex.subtitle,
        muscleGroup: ex.muscleGroup,
        minReps: ex.minReps,
        maxReps: ex.maxReps,
        targetRir: ex.targetRir,
        previousWeightKg: ex.previousWeightKg,
        previousReps: ex.previousReps,
        supersetGroupId: ex.supersetGroupId,
        sets: Array.from({ length: ex.sets }, (_, sIdx) => ({
          setNumber: sIdx + 1,
          weightKg: ex.targetWeightKg,
          reps: defaultReps,
          rir: defaultRirNum,
          completed: done,
        })),
      };
    }),
  };
}
